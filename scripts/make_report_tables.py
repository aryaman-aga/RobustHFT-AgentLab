#!/usr/bin/env python
"""Collect outputs/ tables into a single report.md and LaTeX tables for the paper.

Reads:  outputs/pipeline/pipeline_summary.csv, outputs/ablation/*/ablation_*_summary.csv,
        outputs/models/detector_meta.json, outputs/pipeline/fig_*.png
Writes: outputs/report.md, paper/tables/*.tex, paper/figures/*.png
(paper/ is self-contained so it compiles from a fresh clone, where outputs/ is empty.)
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import pandas as pd

from _common import ROOT, base_parser, parse_overrides

from rhal.config import load_config
from rhal.utils.io import ensure_dir

PCT = {"MER", "ASR", "ASR_net", "ASR_active", "ASR_active_net", "ASR_given_exposed", "exposure_rate", "CR", "CR_clean_paired", "max_drawdown", "hold_rate"}
PAPER_FIGURES = ["fig_frontier.png", "fig_equity.png", "fig_exposure.png"]


def latex_table(agg: pd.DataFrame, cols: list[str], caption: str, label: str, arm_map=None) -> str:
    cols = [c for c in cols if f"{c}_mean" in agg.columns]
    head = " & ".join(["Arm"] + [c.replace("_", "\\_") for c in cols]) + " \\\\"
    lines = ["\\begin{table}[t]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\small",
             "\\begin{tabular}{l" + "r" * len(cols) + "}", "\\toprule", head, "\\midrule"]
    for _, r in agg.iterrows():
        cells = []
        for c in cols:
            m, s = r[f"{c}_mean"], r[f"{c}_std"]
            if pd.isna(m):
                cells.append("--")
            elif c in PCT:
                cells.append(f"{100*m:.1f}$\\pm${100*s:.1f}")
            else:
                cells.append(f"{m:.2f}$\\pm${s:.2f}")
        name = (arm_map(r["arm"]) if arm_map else r["arm"]).replace("_", "\\_")
        lines.append(f"{name} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines)


def md_table(agg: pd.DataFrame, cols: list[str]) -> str:
    cols = [c for c in cols if f"{c}_mean" in agg.columns]
    out = ["| arm | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for _, r in agg.iterrows():
        cells = []
        for c in cols:
            m, s = r[f"{c}_mean"], r[f"{c}_std"]
            cells.append("--" if pd.isna(m) else (f"{100*m:.1f} ± {100*s:.1f}" if c in PCT else f"{m:.2f} ± {s:.2f}"))
        out.append(f"| {r['arm']} | " + " | ".join(cells) + " |")
    return "\n".join(out)


_DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine", ".": "p"}


def _macro_name(*parts: str) -> str:
    out = ""
    for part in parts:
        for tok in part.replace("-", "_").split("_"):
            tok = "".join(_DIGITS.get(ch, ch) for ch in tok)
            out += tok[:1].upper() + tok[1:]
    return out


def emit_numbers(agg_by_prefix: dict[str, pd.DataFrame], extra: dict[str, str], path: Path) -> None:
    r"""Write LaTeX \csname macros so prose numbers in main.tex always match outputs."""
    lines = ["% AUTO-GENERATED by scripts/make_report_tables.py -- do not edit"]

    def put(name: str, val) -> None:
        lines.append(f"\\expandafter\\def\\csname {name}\\endcsname{{{val}}}")

    for prefix, agg in agg_by_prefix.items():
        for _, r in agg.iterrows():
            arm = r["arm"]
            for metric in ["MER", "MER_lift", "ASR", "ASR_net", "ASR_active", "ASR_active_net", "CR", "CR_clean_paired", "max_drawdown", "signal_deviation", "hold_rate"]:
                if f"{metric}_mean" not in agg.columns or pd.isna(r[f"{metric}_mean"]):
                    continue
                m, sd = r[f"{metric}_mean"], r[f"{metric}_std"]
                fmt = (f"{100*m:.1f}", f"{100*sd:.1f}") if metric in PCT else (f"{m:.2f}", f"{sd:.2f}")
                put(_macro_name(prefix, arm, metric), fmt[0])
                put(_macro_name(prefix, arm, metric, "sd"), fmt[1])
    for k, v in extra.items():
        put(k, v)
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    p = base_parser("Build report tables")
    a = p.parse_args()
    cfg = load_config(a.config, parse_overrides(a.set))
    root = Path(a.out or cfg.output_dir)
    tex_dir = ensure_dir(ROOT / "paper" / "tables")
    aggs: dict[str, pd.DataFrame] = {}
    extra: dict[str, str] = {"Nseeds": str(cfg.experiment.n_seeds), "NevalDays": str(cfg.data.eval_days), "NewsPerDay": str(cfg.data.news_per_day), "NDays": str(cfg.data.n_days),
                             "Kappa": f"{cfg.grounding.strength:.1f}", "TopK": str(cfg.retrieval.top_k), "FeeBps": f"{cfg.backtest.fee_bps:.0f}", "SlipBps": f"{cfg.backtest.slippage_bps:.0f}"}
    md = ["# RobustHFT-AgentLab -- experiment report", "", "All numbers: mean ± std over seeds; percentages where applicable. Offline synthetic simulation; not investment advice.", ""]

    pipe = root / "pipeline" / "pipeline_summary.csv"
    if pipe.exists():
        agg = pd.read_csv(pipe)
        order = ["clean__none", "placebo__none", "injected__none", "clean__grounded", "placebo__grounded", "injected__grounded", "clean__grounded_risk", "placebo__grounded_risk", "injected__grounded_risk"]
        agg = agg.set_index("arm").reindex([o for o in order if o in set(agg["arm"])]).reset_index()
        aggs["M"] = agg
        extra["NseedsRun"] = str(int(agg["n_seeds"].iloc[0]))
        cols_attack = ["MER", "MER_lift", "ASR", "ASR_net", "ASR_active", "ASR_active_net", "signal_deviation", "CR", "CR_clean_paired", "max_drawdown", "hold_rate"]
        md += ["## Main results (clean / placebo / injected × defence level)", "", md_table(agg, cols_attack), ""]
        (tex_dir / "main_results.tex").write_text(latex_table(agg, ["MER", "MER_lift", "ASR", "ASR_net", "ASR_active_net", "CR", "max_drawdown"], "Main results on synthetic data (mean$\\pm$std over seeds; \\%). Net ASR $=$ ASR $-$ ASR$_{\\text{placebo}}$.", "tab:main"))
        # defence robustness gain table
        inj = agg[agg["arm"].str.startswith("injected__")].copy()
        inj["defence"] = inj["arm"].str.replace("injected__", "")
        base_asr = float(inj.loc[inj["defence"] == "none", "ASR_mean"].iloc[0]) if (inj["defence"] == "none").any() else float("nan")
        base_net = float(inj.loc[inj["defence"] == "none", "ASR_net_mean"].iloc[0]) if (inj["defence"] == "none").any() else float("nan")
        inj["robustness_gain_ASR"] = base_asr - inj["ASR_mean"]
        inj["robustness_gain_net"] = base_net - inj["ASR_net_mean"]
        for _, r in inj.iterrows():
            extra[_macro_name("Gain", r["defence"], "ASR")] = f"{100*r['robustness_gain_ASR']:.1f}"
            extra[_macro_name("Gain", r["defence"], "ASRnet")] = f"{100*r['robustness_gain_net']:.1f}"
        md += ["## Robustness gain of defences (Δ ASR vs undefended, percentage points)", "", "| defence | ASR | net ASR | active net ASR | gain (ASR) | gain (net) | clean CR | attacked DD |", "|---|---|---|---|---|---|---|---|"]
        for _, r in inj.iterrows():
            act = r.get("ASR_active_net_mean", float("nan"))
            md.append(f"| {r['defence']} | {100*r['ASR_mean']:.1f} | {100*r['ASR_net_mean']:.1f} | {'--' if pd.isna(act) else f'{100*act:.1f}'} | {100*r['robustness_gain_ASR']:+.1f} | {100*r['robustness_gain_net']:+.1f} | {100*r['CR_clean_paired_mean']:+.1f} | {100*r['max_drawdown_mean']:+.1f} |")
        md.append("")

    for group, cols in [("attack", ["MER", "MER_lift", "ASR", "ASR_net", "CR"]), ("defense", ["ASR", "ASR_net", "ASR_active_net", "CR", "CR_clean_paired", "max_drawdown", "hold_rate"]), ("retrieval", ["MER", "ASR", "ASR_net", "CR"]), ("grounding_strength", ["ASR", "ASR_net", "CR", "CR_clean_paired"])]:
        f = root / "ablation" / group / f"ablation_{group}_summary.csv"
        if f.exists():
            agg = pd.read_csv(f)
            aggs[_macro_name("Abl", group)] = agg
            md += [f"## Ablation: {group}", "", md_table(agg, cols), ""]
            (tex_dir / f"ablation_{group}.tex").write_text(latex_table(agg, cols, f"Ablation ({group.replace('_', ' ')}), mean$\\pm$std over seeds.", f"tab:abl_{group}"))

    meta = root / "models" / "detector_meta.json"
    if meta.exists():
        m = json.loads(meta.read_text())
        extra.update({"DetAcc": f"{m['train_acc']:.2f}", "DetThr": f"{m['threshold']:.2f}", "DetFPR": f"{100*m['holdout_clean_fpr_at_threshold']:.0f}", "DetNtrain": str(m["n_clean_train"] + m["n_perturbed"])})
        if "per_type_detection_rate" in m:
            for k, v in m["per_type_detection_rate"].items():
                if isinstance(v, dict):
                    extra[_macro_name("Det", k, "minor")] = f"{100*v['minor']:.0f}"
                    extra[_macro_name("Det", k, "news")] = f"{100*v['news_style']:.0f}"
                    extra[_macro_name("Det", k, "acad")] = f"{100*v['academic_style']:.0f}"
        md += ["## Detectability proxy", "", f"train acc {m['train_acc']:.3f}; threshold {m['threshold']:.3f} at target FPR {m['target_fpr']}; held-out clean FPR {m['holdout_clean_fpr_at_threshold']:.3f}", ""]
        if "per_type_detection_rate" in m:
            md += ["| type | minor | after news rewrite | after academic rewrite |", "|---|---|---|---|"]
            for k, v in m["per_type_detection_rate"].items():
                if isinstance(v, dict):
                    md.append(f"| {k} | {v['minor']:.2f} | {v['news_style']:.2f} | {v['academic_style']:.2f} |")
            md.append("")
            rows = [(k, v) for k, v in m["per_type_detection_rate"].items() if isinstance(v, dict)]
            tex = ["\\begin{table}[t]", "\\centering", "\\caption{Detection rate of the proxy detector by perturbation type, before and after style rewriting (threshold at 10\\% clean FPR).}", "\\label{tab:detector}", "\\small", "\\begin{tabular}{lrrr}", "\\toprule", "Type & Minor & +News & +Academic \\\\", "\\midrule"]
            tex += [f"{k.replace('_', ' ')} & {v['minor']:.2f} & {v['news_style']:.2f} & {v['academic_style']:.2f} \\\\" for k, v in rows]
            tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
            (tex_dir / "detector.tex").write_text("\n".join(tex))

    # figures referenced by paper/main.tex
    fig_dir = ensure_dir(ROOT / "paper" / "figures")
    for fig in PAPER_FIGURES:
        src = root / "pipeline" / fig
        if src.exists():
            shutil.copyfile(src, fig_dir / fig)

    emit_numbers(aggs, extra, tex_dir / "numbers.tex")
    (root / "report.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    print(f"\nwrote {root/'report.md'} and LaTeX tables to {tex_dir}/")


if __name__ == "__main__":
    main()
