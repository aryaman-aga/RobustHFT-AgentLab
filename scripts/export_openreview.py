#!/usr/bin/env python
"""Write the plain-text fields of the OpenReview submission form (paper/aaai/openreview.md).

The abstract on the form must match the PDF, so it is produced from paper/sections/abstract.tex
by expanding the generated number macros (paper/tables/numbers.tex, figmacros.tex) instead of
being retyped. Run after `make report`; `make paper-aaai-zip` runs it too.
"""

from __future__ import annotations

import re

from _common import ROOT

PAPER = ROOT / "paper"
TITLE = "RobustHFT-AgentLab: A Defense Layer Against Misinformation Attacks on LLM-Based Trading Agents"
KEYWORDS = [
    "LLM-based trading agents",
    "financial misinformation",
    "adversarial robustness",
    "defense",
    "temporal grounding",
    "red teaming",
    "retrieval-augmented generation",
]
TLDR = (  # {RelCutGroundedNet} is filled in from the generated numbers
    "Grounding an LLM trading agent's reading of the news in market evidence the attacker cannot edit cuts "
    "misinformation-driven attack success by about {RelCutGroundedNet}%, beats detection filtering and robust "
    "aggregation, and holds with a local LLM, on real BTC-USD prices and under price impact."
)


def load_macros() -> dict[str, str]:
    """Generated values keyed by macro name, e.g. {'CmpNetNone': '18.4', ...}."""
    out: dict[str, str] = {}
    for name in ("numbers.tex", "figmacros.tex"):
        f = PAPER / "tables" / name
        if f.exists():
            out.update(re.findall(r"\\csname ([A-Za-z]+)\\endcsname\{([^}]*)\}", f.read_text()))
    return out


def to_plain(tex: str, m: dict[str, str]) -> str:
    """Expand the paper's macros into plain text (raises KeyError on a missing value)."""

    def val(key: str) -> str:
        return m[key].replace("$<$", "<")

    tex = re.sub(r"\\cmp\{(\w+)\}", lambda g: f"{val(g[1])} pp [{val(g[1] + 'Lo')}, {val(g[1] + 'Hi')}]", tex)
    tex = re.sub(r"\\val\{(\w+)\}", lambda g: val(g[1]), tex)
    tex = tex.replace("\\rhal{}", "RobustHFT-AgentLab").replace("\\pp{}", " pp").replace("\\%", "%")
    tex = re.sub(r"\\emph\{([^}]*)\}", r"\1", tex)
    tex = tex.replace("---", "\u2014").replace("--", "\u2013").replace("~", " ")
    if "\\" in tex:
        raise ValueError(f"unexpanded LaTeX left in the abstract: {tex[tex.index(chr(92)) :][:40]}")
    return " ".join(tex.split())


def main() -> None:
    macros = load_macros()
    abstract = to_plain((PAPER / "sections" / "abstract.tex").read_text(), macros)
    tldr = TLDR.format(RelCutGroundedNet=macros["RelCutGroundedNet"])
    out = PAPER / "aaai" / "openreview.md"
    out.write_text(
        "# OpenReview submission form (FinFM @ AAAI-27)\n\n"
        "Generated by scripts/export_openreview.py from paper/sections/abstract.tex; do not edit by hand.\n\n"
        f"## Title\n\n{TITLE}\n\n"
        f"## Keywords\n\n{', '.join(KEYWORDS)}\n\n"
        f"## TL;DR\n\n{tldr}\n\n"
        f"## Abstract ({len(abstract.split())} words)\n\n{abstract}\n"
    )
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
